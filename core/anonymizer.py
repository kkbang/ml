def _collect_binding_identifier_texts(content_bytes: bytes, node: Node) -> list[str]:
    tokens: list[str] = []
    stack = [node]
    while stack:
        current = stack.pop()
        if not current.is_named:
            continue
        current_type = str(current.type or "")
        lowered_type = current_type.lower()
        if "type" in lowered_type:
            continue
        if current_type in IDENTIFIER_NODE_TYPES:
            token = _decode_node_text(content_bytes, current).strip()
            if token:
                tokens.append(token)
            continue
        explicit_binding_children = []
        if "pair" in lowered_type:
            pair_value_child = _find_child_by_field_names(current, ("pattern", "value", "name"))
            if pair_value_child is not None:
                explicit_binding_children.append(pair_value_child)
        if not explicit_binding_children:
            for field_name in LOCAL_BINDING_FIELD_NAMES:
                child = _find_child_by_field_names(current, (field_name,))
                if child is not None:
                    explicit_binding_children.append(child)
        if explicit_binding_children:
            seen_ranges: set = set()
            for child in reversed(explicit_binding_children):
                child_range = (int(child.start_byte), int(child.end_byte))
                if child_range in seen_ranges:
                    continue
                seen_ranges.add(child_range)
                stack.append(child)
            continue
        for child, field_name in reversed(_iter_named_children_with_field_names(current)):
            child_type = str(child.type or "")
            child_lowered_type = child_type.lower()
            if "type" in child_lowered_type:
                continue
            if field_name in {"type", "value", "right", "body", "condition", "argument", "arguments"}:
                continue
            if field_name in {"key", "property"} and "pair" in lowered_type:
                continue
            stack.append(child)
    return tokens


def _allows_assignment_bindings(language: str) -> bool:
    return language in {"php", "python", "ruby", "shell"}


def _is_assignment_expression_like(node_type: str) -> bool:
    lowered = node_type.lower()
    return "assignment" in lowered and "declaration" not in lowered and "declarator" not in lowered


def _is_plain_binding_target(node: Node) -> bool:
    node_type = str(node.type or "").lower()
    if any(marker in node_type for marker in NON_BINDING_TARGET_NODE_MARKERS):
        return False
    return True


def _collect_binding_target_nodes(node: Node) -> list:
    current_type = str(node.type or "")
    lowered_type = current_type.lower()
    targets = []
    if "declaration" in lowered_type or current_type in {"with_item"} or "spec" in lowered_type:
        for child, field_name in _iter_named_children_with_field_names(node):
            child_type = str(child.type or "")
            child_lowered_type = child_type.lower()
            if field_name in LOCAL_BINDING_FIELD_NAMES:
                targets.append(child)
                continue
            if "declarator" in child_lowered_type and "abstract" not in child_lowered_type:
                targets.append(child)
    if not targets:
        binding_child = _find_child_by_field_names(node, LOCAL_BINDING_FIELD_NAMES)
        if binding_child is not None:
            targets.append(binding_child)
    deduped_targets = []
    seen_ranges: set = set()
    for target in targets:
        target_range = (int(target.start_byte), int(target.end_byte))
        if target_range in seen_ranges:
            continue
        seen_ranges.add(target_range)
        deduped_targets.append(target)
    return deduped_targets


def _collect_local_binding_symbols(content_bytes: bytes, node: Node, language: str) -> set[str]:
    local_symbols: set[str] = set()
    allow_assignment_bindings = _allows_assignment_bindings(language)
    stack = [node]
    while stack:
        current = stack.pop()
        if not current.is_named:
            continue
        current_type = str(current.type or "")
        if _is_import_like_node(current_type):
            stack.extend(reversed(list(current.children)))
            continue
        binding_targets = _collect_binding_target_nodes(current)
        lowered_type = current_type.lower()
        if binding_targets and (_is_local_variable_like_node(current_type) or "parameter" in lowered_type):
            if _is_assignment_expression_like(current_type):
                if not allow_assignment_bindings or any(not _is_plain_binding_target(bt) for bt in binding_targets):
                    stack.extend(reversed(list(current.children)))
                    continue
            for binding_target in binding_targets:
                local_symbols.update(_ordered_unique_set(_collect_binding_identifier_texts(content_bytes, binding_target)))
        parameter_child = _find_parameter_container(current)
        if parameter_child is not None:
            local_symbols.update(_ordered_unique_set(_collect_binding_identifier_texts(content_bytes, parameter_child)))
        stack.extend(reversed(list(current.children)))
    return local_symbols


def _collect_nested_symbol_names(content_bytes: bytes, node: Node, language: str) -> tuple:
    function_symbols: set[str] = set()
    class_symbols: set[str] = set()
    stack = list(reversed(list(node.children)))
    while stack:
        current = stack.pop()
        if not current.is_named:
            continue
        chunk_type = _node_matches_chunk_type(language, current)
        if chunk_type is not None and not _should_skip_decorated_python_node(language, current):
            if (language in {"javascript", "typescript"} and chunk_type == "function"
                    and str(current.type or "") == "arrow_function"
                    and _is_inline_callback_arrow_function(current)):
                stack.extend(reversed(list(current.children)))
                continue
            symbol_name = _extract_symbol_name(content_bytes, current).strip()
            if symbol_name:
                if chunk_type == "function":
                    function_symbols.add(symbol_name)
                elif chunk_type == "class":
                    class_symbols.add(symbol_name)
        stack.extend(reversed(list(current.children)))
    return function_symbols, class_symbols


def _build_anonymization_context(content_bytes: bytes, node: Node, language: str) -> AnonymizationContext:
    imported_symbols = _collect_imported_symbols(content_bytes, node)
    parameter_symbols = _collect_parameter_symbols(content_bytes, node)
    local_variable_symbols = _collect_local_binding_symbols(content_bytes, node, language)
    local_function_symbols, local_class_symbols = _collect_nested_symbol_names(content_bytes, node, language)
    decorator_symbols = _collect_decorator_symbols(content_bytes, node, language)
    local_variable_symbols -= imported_symbols
    local_variable_symbols -= parameter_symbols
    local_function_symbols -= imported_symbols
    local_class_symbols -= imported_symbols
    return AnonymizationContext(
        imported_symbols=imported_symbols,
        parameter_symbols=parameter_symbols,
        local_variable_symbols=local_variable_symbols,
        local_function_symbols=local_function_symbols,
        local_class_symbols=local_class_symbols,
        decorator_symbols=decorator_symbols,
    )


def _collect_comment_ranges(node: Node) -> list:
    ranges = []
    stack = [node]
    while stack:
        current = stack.pop()
        node_type = str(current.type or "")
        if "comment" in node_type:
            ranges.append((current.start_byte, current.end_byte))
        stack.extend(reversed(list(current.children)))
    ranges.sort()
    return ranges


def _remove_comment_ranges(raw_bytes: bytes, comment_ranges: list, start_byte: int) -> bytes:
    if not comment_ranges:
        return raw_bytes
    pieces = []
    cursor = start_byte
    end_byte = start_byte + len(raw_bytes)
    for comment_start, comment_end in comment_ranges:
        bounded_start = max(start_byte, min(comment_start, end_byte))
        bounded_end = max(start_byte, min(comment_end, end_byte))
        if bounded_start > cursor:
            pieces.append(raw_bytes[cursor - start_byte: bounded_start - start_byte])
        cursor = max(cursor, bounded_end)
    if cursor < end_byte:
        pieces.append(raw_bytes[cursor - start_byte: end_byte - start_byte])
    return b"".join(pieces)


def _normalize_code(raw_code: str, raw_bytes: bytes, node: Node) -> str:
    comment_ranges = _collect_comment_ranges(node)
    normalized_bytes = _remove_comment_ranges(raw_bytes, comment_ranges, node.start_byte)
    normalized_text = normalized_bytes.decode("utf-8", errors="ignore")
    collapsed_lines = []
    previous_blank = False
    for line in normalized_text.splitlines():
        compact_line = re.sub(r"[ \t]+", " ", line.rstrip())
        if not compact_line.strip():
            if previous_blank:
                continue
            collapsed_lines.append("")
            previous_blank = True
            continue
        collapsed_lines.append(compact_line)
        previous_blank = False
    return "\n".join(collapsed_lines).strip()


