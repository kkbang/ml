def _normalize_call_target_text(raw_text: str) -> str:
    normalized = re.sub(r"\s+", "", raw_text.strip())
    if not normalized:
        return ""
    normalized = re.sub(r"\[[^\[\]]*\]", "", normalized)
    normalized = re.sub(r"`[^`]*`", "", normalized)
    previous = None
    while previous != normalized:
        previous = normalized
        normalized = re.sub(r"\([^()]*\)", "", normalized)
    if normalized.startswith("new") and len(normalized) > 3 and normalized[3].isalpha():
        normalized = normalized[3:]
    if normalized.startswith("$."):
        identifiers = IDENTIFIER_TEXT_RE.findall(normalized)
        candidate = "$." + ".".join(identifiers)
        return candidate if SIMPLE_CALL_PATH_RE.fullmatch(candidate) else ""
    if "." in normalized or "::" in normalized or "->" in normalized:
        return normalized if SIMPLE_CALL_PATH_RE.fullmatch(normalized) else ""
    identifier_matches = IDENTIFIER_TEXT_RE.findall(normalized)
    if not identifier_matches:
        return ""
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", normalized):
        return normalized
    return identifier_matches[-1]


def _extract_shell_command_name(content_bytes: bytes, node: Node) -> str:
    command_name_child = _find_child_by_field_names(node, ("name", "command"))
    if command_name_child is not None:
        return _normalize_call_target_text(_decode_node_text(content_bytes, command_name_child))
    for child in node.children:
        if not child.is_named:
            continue
        child_type = str(child.type or "")
        if child_type == "command_name":
            return _normalize_call_target_text(_decode_node_text(content_bytes, child))
    return ""


def _extract_ruby_call_token(raw_text: str) -> str:
    normalized = raw_text.strip()
    if not normalized:
        return ""
    normalized = normalized.split("{", 1)[0].strip()
    normalized = re.split(r"\bdo\b", normalized, maxsplit=1)[0].strip()
    normalized = re.sub(r"\s+", "", normalized)
    previous = None
    while previous != normalized:
        previous = normalized
        normalized = re.sub(r"\([^()]*\)$", "", normalized)
    dotted_match = re.match(r"((?:self|[A-Za-z_][A-Za-z0-9_]*)(?:(?:\.|::)[A-Za-z_][A-Za-z0-9_]*[!?=]?)*)", normalized)
    if dotted_match:
        return dotted_match.group(1)
    receiver_suffix_match = re.search(r"(?:\.|::)([A-Za-z_][A-Za-z0-9_]*[!?=]?)$", normalized)
    if receiver_suffix_match:
        return receiver_suffix_match.group(1)
    bare_match = re.match(r"([A-Za-z_][A-Za-z0-9_]*[!?=]?)", normalized)
    if bare_match:
        return bare_match.group(1)
    return ""


def _extract_call_token_from_node(content_bytes: bytes, node: Node, *, language: str) -> str:
    raw_text = _decode_node_text(content_bytes, node)
    if language == "ruby":
        ruby_token = _extract_ruby_call_token(raw_text)
        if ruby_token:
            return ruby_token
    if language == "shell":
        shell_token = _extract_shell_command_name(content_bytes, node)
        if shell_token:
            return shell_token
    raw_token = _normalize_call_target_text(raw_text)
    if raw_token and ("." in raw_token or "::" in raw_token or "->" in raw_token or raw_text.lstrip().startswith("new ")):
        return raw_token
    callee = _find_child_by_field_names(node, CALL_FIELD_NAMES)
    if callee is None:
        named_children = [child for child in node.children if child.is_named]
        if not named_children:
            return raw_token
        callee = named_children[0]
    callee_token = _normalize_call_target_text(_decode_node_text(content_bytes, callee))
    return callee_token or raw_token


