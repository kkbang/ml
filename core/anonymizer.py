def _extract_operator_tokens_from_gap(gap_text: str) -> list[str]:
    if not gap_text.strip():
        return []
    tokens = []
    seen: set[str] = set()
    for match in OPERATOR_SYMBOL_PATTERN.finditer(gap_text):
        token = OPERATOR_SYMBOL_TO_TOKEN.get(match.group(0))
        if token and token not in seen:
            tokens.append(token)
            seen.add(token)
    lowered_gap = f" {gap_text.lower()} "
    for keyword_token, token in ((" and ", "and"), (" or ", "or"), (" not ", "not")):
        if keyword_token in lowered_gap and token not in seen:
            tokens.append(token)
            seen.add(token)
    return tokens


def _collect_operator_tokens(content_bytes: bytes, node: Node) -> list[str]:
    ordered = []
    seen: set[str] = set()
    stack = [node]
    while stack:
        current = stack.pop()
        if not current.is_named:
            continue
        current_type = str(current.type or "").lower()
        named_children = [child for child in current.children if child.is_named]
        if "assignment" in current_type and "assign" not in seen:
            ordered.append("assign")
            seen.add("assign")
        if len(named_children) >= 2 and ("binary" in current_type or "comparison" in current_type
                or "member" in current_type or "selector" in current_type
                or "attribute" == current_type or "qualified_identifier" == current_type):
            previous_child = named_children[0]
            for child in named_children[1:]:
                gap_text = content_bytes[previous_child.end_byte: child.start_byte].decode("utf-8", errors="ignore")
                for token in _extract_operator_tokens_from_gap(gap_text):
                    if token not in seen:
                        ordered.append(token)
                        seen.add(token)
                previous_child = child
        if "unary" in current_type and named_children:
            first_child = named_children[0]
            prefix_text = content_bytes[current.start_byte: first_child.start_byte].decode("utf-8", errors="ignore")
            for token in _extract_operator_tokens_from_gap(prefix_text):
                if token not in seen:
                    ordered.append(token)
                    seen.add(token)
        stack.extend(reversed(named_children))
    return ordered


def _collect_ast_node_sequence(node: Node, *, cap: int) -> list[str]:
    sequence = []
    stack = [node]
    while stack and len(sequence) < max(1, cap):
        current = stack.pop()
        if not current.is_named:
            continue
        current_type = str(current.type or "")
        if not current_type or current_type in SIGNIFICANT_NODE_SKIP_TYPES:
            stack.extend(reversed([child for child in current.children if child.is_named]))
            continue
        sequence.append(current_type)
        stack.extend(reversed([child for child in current.children if child.is_named]))
    return sequence


def _build_structure_signature(chunk_type: str, ast_node_sequence: list[str]) -> str:
    parts = [chunk_type]
    for node_type in ast_node_sequence:
        lowered = node_type.lower()
        node_tokens = {token for token in re.split(r"[^a-z0-9]+|_", lowered) if token}
        for marker, category in STRUCTURE_NODE_CATEGORIES:
            if any(token == marker or token.rstrip("s") == marker for token in node_tokens) and category not in parts:
                parts.append(category)
                break
        if len(parts) >= 6:
            break
    return "|".join(parts)


def _collect_control_flow_tags(*, ast_node_sequence: list[str], symbol_name: str, call_tokens: list[str]) -> list[str]:
    tags = []
    seen: set[str] = set()
    lowered_node_types = [node_type.lower() for node_type in ast_node_sequence]
    for node_type, tag in CONTROL_FLOW_NODE_TYPE_TAGS:
        if any(node_type in lowered for lowered in lowered_node_types) and tag not in seen:
            tags.append(tag)
            seen.add(tag)
    is_recursive = False
    if symbol_name:
        for token in call_tokens:
            if token == symbol_name:
                is_recursive = True
                break
            recursive_match = SELF_RECURSIVE_CALL_RE.match(token)
            if recursive_match and recursive_match.group("name") == symbol_name:
                is_recursive = True
                break
    if is_recursive and "recursion" not in seen:
        tags.append("recursion")
        seen.add("recursion")
    if not tags:
        return ["none"]
    return tags


def _looks_like_external_pascal_symbol(token: str, *, local_symbols: set[str]) -> bool:
    if token in local_symbols:
        return False
    if not token or "_" in token:
        return False
    if not token[0].isupper():
        return False
    return any(char.islower() for char in token[1:])


def _iter_string_ranges(code: str, *, language: str) -> list:
    ranges = []
    index = 0
    code_length = len(code)
    allow_single_quote = language in SINGLE_QUOTED_STRING_LANGUAGES
    while index < code_length:
        current = code[index]
        if current not in {'"', "`"} and not (current == "'" and allow_single_quote):
            index += 1
            continue
        start = index
        if current in {"'", '"'}:
            prefix_start = index
            while prefix_start > 0 and code[prefix_start - 1] in STRING_PREFIX_CHARS:
                prefix_start -= 1
            if prefix_start < index:
                before_prefix = code[prefix_start - 1] if prefix_start > 0 else ""
                if not before_prefix or (not before_prefix.isalnum() and before_prefix != "_"):
                    start = prefix_start
        triple_quoted = (current in {"'", '"'} and index + 2 < code_length
                         and code[index + 1] == current and code[index + 2] == current)
        cursor = index + (3 if triple_quoted else 1)
        if current == "`":
            while cursor < code_length:
                if code[cursor] == "\\":
                    cursor += 2
                    continue
                if code[cursor] == "`":
                    cursor += 1
                    break
                cursor += 1
        elif triple_quoted:
            while cursor < code_length:
                if code[cursor] == "\\":
                    cursor += 2
                    continue
                if (cursor + 2 < code_length and code[cursor] == current
                        and code[cursor + 1] == current and code[cursor + 2] == current):
                    cursor += 3
                    break
                cursor += 1
        else:
            while cursor < code_length:
                if code[cursor] == "\\":
                    cursor += 2
                    continue
                if code[cursor] == current:
                    cursor += 1
                    break
                cursor += 1
        ranges.append((start, min(cursor, code_length)))
        index = max(cursor, index + 1)
    return ranges


def _preserved_symbols_for_language(language: str) -> set[str]:
    normalized_language = str(language or "").strip().lower()
    if normalized_language == "python":
        return set(PYTHON_BUILTIN_SYMBOLS) | set(PYTHON_WELL_KNOWN_API_SYMBOLS)
    if normalized_language in {"javascript", "typescript"}:
        return set(JAVASCRIPT_COMMON_GLOBALS) | set(JAVASCRIPT_WELL_KNOWN_API_SYMBOLS)
    if normalized_language == "ruby":
        return set(RUBY_COMMON_SYMBOLS)
    if normalized_language == "php":
        return set(PHP_COMMON_SYMBOLS)
    if normalized_language == "shell":
        return set(SHELL_COMMON_SYMBOLS)
    return set()


def _previous_non_whitespace_char(text: str, index: int) -> str:
    cursor = index - 1
    while cursor >= 0 and text[cursor].isspace():
        cursor -= 1
    return text[cursor] if cursor >= 0 else ""


def _previous_non_whitespace_index(text: str, index: int) -> int:
    cursor = index - 1
    while cursor >= 0 and text[cursor].isspace():
        cursor -= 1
    return cursor


def _next_non_whitespace_char(text: str, index: int) -> str:
    cursor = index
    text_length = len(text)
    while cursor < text_length and text[cursor].isspace():
        cursor += 1
    return text[cursor] if cursor < text_length else ""


def _next_non_whitespace_index(text: str, index: int) -> int:
    cursor = index
    text_length = len(text)
    while cursor < text_length and text[cursor].isspace():
        cursor += 1
    return cursor if cursor < text_length else -1


def _has_member_or_namespace_prefix(text: str, start: int) -> bool:
    previous_index = _previous_non_whitespace_index(text, start)
    if previous_index < 0:
        return False
    previous_char = text[previous_index]
    earlier_index = _previous_non_whitespace_index(text, previous_index)
    earlier_char = text[earlier_index] if earlier_index >= 0 else ""
    if previous_char == ".":
        if earlier_char == ".":
            return False
        return True
    if previous_char == ":" and earlier_char == ":":
        return True
    if previous_char == ">" and earlier_char == "-":
        return True
    return previous_char == "\\"


def _is_object_key_or_shorthand_context(text: str, start: int, end: int) -> bool:
    previous_index = _previous_non_whitespace_index(text, start)
    previous_char = text[previous_index] if previous_index >= 0 else ""
    next_char = _next_non_whitespace_char(text, end)
    if previous_char == "{" and previous_index > 0 and text[previous_index - 1] in {"#", "$"}:
        return False
    return previous_char in "{," and next_char == ":"


def _find_enclosing_delimiter_index(text: str, index: int, *, opener: str, closer: str) -> int:
    depth = 0
    cursor = index - 1
    while cursor >= 0:
        char = text[cursor]
        if char == closer:
            depth += 1
        elif char == opener:
            if depth == 0:
                return cursor
            depth -= 1
        cursor -= 1
    return -1


def _is_probable_python_call_context(text: str, open_index: int) -> bool:
    prefix = text[:open_index]
    if re.search(r"\b(def|class)\s+[A-Za-z_][A-Za-z0-9_]*\s*$", prefix):
        return False
    previous_index = _previous_non_whitespace_index(text, open_index)
    if previous_index < 0:
        return False
    previous_char = text[previous_index]
    if previous_char in {")", "]", "}", "."}:
        return True
    return previous_char.isalnum() or previous_char == "_"


def _is_python_keyword_argument_context(text: str, start: int, end: int) -> bool:
    previous_index = _previous_non_whitespace_index(text, start)
    previous_char = text[previous_index] if previous_index >= 0 else ""
    next_index = _next_non_whitespace_index(text, end)
    if next_index < 0 or previous_char not in {"(", ","}:
        return False
    if text[next_index: next_index + 2] in {"==", "=>"}:
        return False
    if text[next_index] != "=":
        return False
    open_index = _find_enclosing_delimiter_index(text, start, opener="(", closer=")")
    if open_index < 0:
        return False
    return _is_probable_python_call_context(text, open_index)


def _is_csharp_initializer_key_context(text: str, start: int, end: int) -> bool:
    previous_index = _previous_non_whitespace_index(text, start)
    previous_char = text[previous_index] if previous_index >= 0 else ""
    next_index = _next_non_whitespace_index(text, end)
    if next_index < 0 or previous_char not in {"{", ","}:
        return False
    if text[next_index: next_index + 2] in {"==", "=>"}:
        return False
    if text[next_index] != "=":
        return False
    open_index = _find_enclosing_delimiter_index(text, start, opener="{", closer="}")
    if open_index < 0:
        return False
    window_start = max(0, open_index - 120)
    return bool(re.search(r"\bnew\b", text[window_start:open_index]))


def _is_named_assignment_key_context(language: str, text: str, start: int, end: int) -> bool:
    if language == "python":
        return _is_python_keyword_argument_context(text, start, end)
    if language == "csharp":
        return _is_csharp_initializer_key_context(text, start, end)
    return False


def _should_preserve_identifier_context(language: str, text: str, start: int, end: int) -> bool:
    if _has_member_or_namespace_prefix(text, start):
        return True
    if _is_named_assignment_key_context(language, text, start, end):
        return True
    if language in {"javascript", "typescript"} and _is_object_key_or_shorthand_context(text, start, end):
        return True
    return False


def _replace_identifiers_in_segment(segment: str, *, absolute_start: int, replace_token: Any) -> str:
    parts = []
    cursor = 0
    for match in IDENTIFIER_RE.finditer(segment):
        start, end = match.span()
        parts.append(segment[cursor:start])
        parts.append(replace_token(match.group(0), absolute_start + start, absolute_start + end))
        cursor = end
    parts.append(segment[cursor:])
    return "".join(parts)


def _normalize_string_fragment(fragment: str, *, string_replacements: dict, next_string_index: list) -> str:
    replacement = string_replacements.get(fragment)
    if replacement is not None:
        return replacement
    replacement = f"STR_{next_string_index[0]}"
    next_string_index[0] += 1
    string_replacements[fragment] = replacement
    return replacement


def _should_preserve_string_literal_content(language: str, content: str) -> bool:
    if language not in {"javascript", "typescript"}:
        return False
    stripped = str(content or "").strip()
    if not stripped:
        return False
    lowered = stripped.lower()
    if lowered in JAVASCRIPT_UI_TAG_LITERALS:
        return True
    if JAVASCRIPT_UI_CLASS_LITERAL_RE.fullmatch(stripped):
        return True
    if JAVASCRIPT_SELECTOR_LITERAL_RE.fullmatch(stripped):
        return True
    if "<" in stripped and ">" in stripped and any(m in lowered for m in ("<svg", "</", "<div", "<span", "<path", "<button")):
        return True
    return False


def _split_string_literal_segment(segment: str):
    if not segment:
        return None
    quote_index = 0
    while quote_index < len(segment) and segment[quote_index] in STRING_PREFIX_CHARS:
        quote_index += 1
    if quote_index >= len(segment):
        return None
    quote_char = segment[quote_index]
    if quote_char == "`":
        if len(segment) < quote_index + 2:
            return None
        return segment[:quote_index], "`", segment[quote_index + 1: -1], "`"
    if quote_char not in {"'", '"'}:
        return None
    triple = segment[quote_index: quote_index + 3] == quote_char * 3
    opener = quote_char * (3 if triple else 1)
    opener_len = len(opener)
    if len(segment) < quote_index + opener_len * 2:
        return None
    prefix = segment[:quote_index]
    content_start = quote_index + opener_len
    content_end = len(segment) - opener_len
    return prefix, opener, segment[content_start:content_end], opener


def _normalize_string_literal_segment(*, language: str, segment: str, absolute_start: int,
                                       replace_token: Any, string_replacements: dict, next_string_index: list) -> str:
    parsed = _split_string_literal_segment(segment)
    if parsed is None:
        return segment
    prefix, opener, content, closer = parsed
    if _should_preserve_string_literal_content(language, content):
        return segment
    if language == "shell" and "$" in content:
        parts = []
        cursor = 0
        inner_offset = len(prefix) + len(opener)
        for match in SHELL_VARIABLE_EXPANSION_RE.finditer(content):
            literal_fragment = content[cursor: match.start()]
            if literal_fragment:
                parts.append(_normalize_string_fragment(literal_fragment, string_replacements=string_replacements, next_string_index=next_string_index))
            if match.group(1) is not None:
                token_start, _ = match.span(1)
                parts.append("${")
                parts.append(_replace_identifiers_in_segment(match.group(1), absolute_start=absolute_start + inner_offset + token_start, replace_token=replace_token))
                parts.append("}")
            else:
                token_start, _ = match.span(2)
                parts.append("$")
                parts.append(_replace_identifiers_in_segment(match.group(2), absolute_start=absolute_start + inner_offset + token_start, replace_token=replace_token))
            cursor = match.end()
        if parts:
            trailing_fragment = content[cursor:]
            if trailing_fragment:
                parts.append(_normalize_string_fragment(trailing_fragment, string_replacements=string_replacements, next_string_index=next_string_index))
            return f"{prefix}{opener}{''.join(parts)}{closer}"
    interpolation_pattern = None
    if language == "ruby":
        interpolation_pattern = re.compile(r"#\{([^{}]+)\}")
    elif language == "python" and re.match(r"(?i)^[rubf]*f[rubf]*(['\"]{1,3})", segment):
        interpolation_pattern = re.compile(r"\{([^{}]+)\}")
    elif language in {"javascript", "typescript"} and opener == "`":
        interpolation_pattern = re.compile(r"\$\{([^{}]+)\}")
    if interpolation_pattern is None:
        replacement = _normalize_string_fragment(content, string_replacements=string_replacements, next_string_index=next_string_index)
        return f"{prefix}{opener}{replacement}{closer}"
    parts = []
    cursor = 0
    inner_offset = len(prefix) + len(opener)
    for match in interpolation_pattern.finditer(content):
        literal_fragment = content[cursor: match.start()]
        if literal_fragment:
            parts.append(_normalize_string_fragment(literal_fragment, string_replacements=string_replacements, next_string_index=next_string_index))
        expression_start, expression_end = match.span(1)
        parts.append(content[match.start(): expression_start])
        parts.append(_replace_identifiers_in_segment(content[expression_start:expression_end], absolute_start=absolute_start + inner_offset + expression_start, replace_token=replace_token))
        parts.append(content[expression_end: match.end()])
        cursor = match.end()
    trailing_fragment = content[cursor:]
    if trailing_fragment:
        parts.append(_normalize_string_fragment(trailing_fragment, string_replacements=string_replacements, next_string_index=next_string_index))
    return f"{prefix}{opener}{''.join(parts)}{closer}"


def _anonymize_class_code(normalized_code: str, symbol_name: str) -> str:
    if not symbol_name:
        return normalized_code
    replacement_done = False

    def replace_first(match: re.Match) -> str:
        nonlocal replacement_done
        token = match.group(0)
        if replacement_done or token != symbol_name:
            return token
        replacement_done = True
        return "CLASS_0"

    return IDENTIFIER_RE.sub(replace_first, normalized_code)


def _anonymize_code(*, language: str, normalized_code: str, symbol_name: str, chunk_type: str,
                    call_tokens: list[str], imported_symbols: set[str], parameter_symbols: set[str],
                    local_variable_symbols: set[str], local_function_symbols: set[str],
                    local_class_symbols: set[str], decorator_symbols: set[str]) -> AnonymizationResult:
    preserve_top_level_symbol = language in PARTIAL_ANONYMIZATION_LANGUAGES
    if chunk_type == "class":
        if preserve_top_level_symbol:
            return AnonymizationResult(code=normalized_code, replacements={})
        anonymized_code = _anonymize_class_code(normalized_code, symbol_name)
        replacements = {symbol_name: "CLASS_0"} if symbol_name and anonymized_code != normalized_code else {}
        return AnonymizationResult(code=anonymized_code, replacements=replacements)

    preserve_exact: set[str] = set(COMMON_RESERVED_WORDS)
    preserve_exact.update(_preserved_symbols_for_language(language))
    preserve_exact.update(imported_symbols)
    preserve_exact.update(decorator_symbols)
    local_symbols = parameter_symbols | local_variable_symbols | local_function_symbols | local_class_symbols
    for token in call_tokens:
        parts = [part for part in token.split(".") if part]
        if not parts or len(parts) == 1:
            continue
        if parts[0] not in local_symbols:
            preserve_exact.add(parts[0])
        preserve_exact.update(parts[1:])
    preserve_lowered = {token.lower() for token in preserve_exact} if language == "sql" else set()

    replacements: dict[str, str] = {}
    string_replacements: dict[str, str] = {}
    next_string_index = [0]
    next_arg_index = 0
    next_var_index = 0
    next_function_index = 1
    next_class_index = 1
    symbol_alias = symbol_name if preserve_top_level_symbol and symbol_name else "FUNC_0"

    def replace_token(token: str, start: int, end: int) -> str:
        nonlocal next_arg_index, next_var_index, next_function_index, next_class_index
        lowered = token.lower()
        if _should_preserve_identifier_context(language, normalized_code, start, end):
            return token
        if token == symbol_name and symbol_name:
            return symbol_alias
        if token in preserve_exact or lowered in preserve_lowered or (token.startswith("__") and token.endswith("__")):
            return token
        if _looks_like_external_pascal_symbol(token, local_symbols=local_symbols):
            return token
        replacement = replacements.get(token)
        if replacement is not None:
            return replacement
        if token in parameter_symbols and language in PARTIAL_ANONYMIZATION_LANGUAGES:
            replacement = f"ARG_{next_arg_index}"
            next_arg_index += 1
        elif token in local_class_symbols:
            replacement = f"CLASS_{next_class_index}"
            next_class_index += 1
        elif token in local_function_symbols:
            replacement = f"FUNC_{next_function_index}"
            next_function_index += 1
        elif token in local_variable_symbols:
            replacement = f"VAR_{next_var_index}"
            next_var_index += 1
        else:
            return token
        replacements[token] = replacement
        return replacement

    parts = []
    cursor = 0
    for start, end in _iter_string_ranges(normalized_code, language=language):
        if start > cursor:
            parts.append(_replace_identifiers_in_segment(normalized_code[cursor:start], absolute_start=cursor, replace_token=replace_token))
        parts.append(_normalize_string_literal_segment(language=language, segment=normalized_code[start:end], absolute_start=start, replace_token=replace_token, string_replacements=string_replacements, next_string_index=next_string_index))
        cursor = end
    if cursor < len(normalized_code):
        parts.append(_replace_identifiers_in_segment(normalized_code[cursor:], absolute_start=cursor, replace_token=replace_token))
    return AnonymizationResult(code="".join(parts), replacements=dict(replacements))


def _has_unreplaced_local_occurrence(*, language: str, code: str, replacements: dict[str, str]) -> bool:
    if not replacements:
        return False
    replaced_tokens = set(replacements.keys())
    cursor = 0
    for start, end in _iter_string_ranges(code, language=language):
        if start > cursor:
            segment = code[cursor:start]
            for match in IDENTIFIER_RE.finditer(segment):
                token = match.group(0)
                if token not in replaced_tokens:
                    continue
                absolute_start = cursor + match.start()
                absolute_end = cursor + match.end()
                if _should_preserve_identifier_context(language, code, absolute_start, absolute_end):
                    continue
                return True
        cursor = end
    if cursor < len(code):
        segment = code[cursor:]
        for match in IDENTIFIER_RE.finditer(segment):
            token = match.group(0)
            if token not in replaced_tokens:
                continue
            absolute_start = cursor + match.start()
            absolute_end = cursor + match.end()
            if _should_preserve_identifier_context(language, code, absolute_start, absolute_end):
                continue
            return True
    return False


def collect_symbol_spans(content_bytes: bytes, language: str, tree: Tree) -> list[SymbolSpan]:
    root = tree.root_node
    stack = [root]
    spans = []
    seen_ranges: set = set()
    while stack:
        node = stack.pop()
        stack.extend(reversed(list(node.children)))
        chunk_type = _node_matches_chunk_type(language, node)
        if chunk_type is None or _should_skip_decorated_python_node(language, node):
            continue
        line_start = int(node.start_point[0]) + 1
        line_end = int(node.end_point[0]) + 1
        if line_start <= 0 or line_end < line_start:
            continue
        symbol_target = node
        if language == "python" and str(node.type or "") == "decorated_definition":
            decorated_target = _get_decorated_python_target(node)
            if decorated_target is not None:
                symbol_target = decorated_target
        symbol_name = _extract_symbol_name(content_bytes, symbol_target)
        param_count = _estimate_param_count(_decode_node_text(content_bytes, symbol_target)) if chunk_type == "function" else 0
        range_key = (chunk_type, line_start, line_end, symbol_name)
        if range_key in seen_ranges:
            continue
        seen_ranges.add(range_key)
        spans.append(SymbolSpan(chunk_type=chunk_type, symbol_type=chunk_type, symbol_name=symbol_name,
                                param_count=param_count, line_start=line_start, line_end=line_end,
                                start_byte=int(node.start_byte), end_byte=int(node.end_byte), node_type=str(node.type or "")))
    spans.sort(key=lambda span: (span.line_start, span.line_end, span.chunk_type, span.symbol_name))
    return spans


def _is_inline_callback_arrow_function(node: Node) -> bool:
    current = getattr(node, "parent", None)
    depth = 0
    while current is not None and depth < 5:
        current_type = str(current.type or "")
        if current_type in INLINE_CALLBACK_ANCESTOR_TYPES:
            return True
        if current_type in NAMED_ARROW_PARENT_TYPES:
            return False
        current = getattr(current, "parent", None)
        depth += 1
    return False


def _is_trivial_candidate(*, span: SymbolSpan, node: Node, language: str, normalized_code: str,
                           identifier_tokens: list[str], call_tokens: list[str], ast_node_sequence: list[str],
                           structure_signature: str, nested_function_symbols: set[str]) -> bool:
    node_type = str(span.node_type or "")
    node_type_tokens = _node_type_tokens(node_type)
    ast_types = set(ast_node_sequence)
    if language in {"c", "cpp"} and node_type == "function_declarator":
        return True
    if language == "go" and node_type == "struct_type":
        return True
    if language in {"php", "javascript", "typescript"} and node_type in {"function_call_expression", "member_call_expression"}:
        return True
    if span.chunk_type == "function":
        if node_type in PARAMETER_CONTAINER_TYPES or "parameter" in node_type_tokens:
            return True
        if ast_types and ast_types.issubset(TRIVIAL_ONLY_AST_NODE_TYPES):
            return True
        if structure_signature == "function|params" and not call_tokens:
            return True
        if node_type == "arrow_function" and not identifier_tokens and not call_tokens:
            return True
        if language in {"javascript", "typescript"} and node_type == "arrow_function" and _is_inline_callback_arrow_function(node):
            return True
        if normalized_code.strip() in {"()", "{}"}:
            return True
    if span.chunk_type == "class":
        if nested_function_symbols:
            return True
        if ast_types and ast_types.issubset(TRIVIAL_CLASS_AST_NODE_TYPES):
            return True
    return False


def _split_top_level_csv(text: str) -> list[str]:
    if not text.strip():
        return []
    parts = []
    current = []
    depths = {"(": 0, "[": 0, "{": 0, "<": 0}
    closing_to_opening = {")": "(", "]": "[", "}": "{", ">": "<"}
    string_delimiter = ""
    escape = False
    for char in text:
        if string_delimiter:
            current.append(char)
            if escape:
                escape = False
                continue
            if char == "\\":
                escape = True
                continue
            if char == string_delimiter:
                string_delimiter = ""
            continue
        if char in {"'", '"', "`"}:
            string_delimiter = char
            current.append(char)
            continue
        if char in depths:
            depths[char] += 1
            current.append(char)
            continue
        if char in closing_to_opening:
            opening = closing_to_opening[char]
            if depths[opening] > 0:
                depths[opening] -= 1
            current.append(char)
            continue
        if char == "," and not any(depths.values()):
            part = "".join(current).strip()
            if part:
                parts.append(part)
            current = []
            continue
        current.append(char)
    trailing = "".join(current).strip()
    if trailing:
        parts.append(trailing)
    return parts


def _extract_js_ts_header_parameter_names(normalized_code: str) -> set[str]:
    if not normalized_code.strip():
        return set()
    header_lines = normalized_code.splitlines()[:4]
    header_text = " ".join(line.strip() for line in header_lines if line.strip())
    if not header_text:
        return set()
    header_end = len(header_text)
    arrow_index = header_text.find("=>")
    brace_index = header_text.find("{")
    if arrow_index >= 0:
        header_end = min(header_end, arrow_index)
    if brace_index >= 0:
        header_end = min(header_end, brace_index)
    header_text = header_text[:header_end]
    open_index = header_text.find("(")
    close_index = header_text.rfind(")")
    if open_index < 0 or close_index <= open_index:
        return set()
    parameter_names: set[str] = set()
    parameter_text = header_text[open_index + 1: close_index]
    for part in _split_top_level_csv(parameter_text):
        cleaned = re.sub(r"^\.\.\.", "", part.strip())
        cleaned = cleaned.split("=", 1)[0].strip()
        cleaned = cleaned.split(":", 1)[0].strip()
        if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", cleaned):
            parameter_names.add(cleaned)
    return parameter_names


def _canonicalize_named_arrow_function_code(anonymized_code: str, *, node_type: str, symbol_name: str) -> str:
    if node_type != "arrow_function" or not symbol_name or not anonymized_code.strip():
        return anonymized_code
    stripped = anonymized_code.lstrip()
    if stripped.startswith(("const FUNC_0 =", "let FUNC_0 =", "var FUNC_0 =")):
        return anonymized_code
    if not (stripped.startswith("(") or stripped.startswith("async ") or re.match(r"^[A-Za-z_$][A-Za-z0-9_$]*\s*=>", stripped)):
        return anonymized_code
    leading = anonymized_code[: len(anonymized_code) - len(stripped)]
    return f"{leading}const FUNC_0 = {stripped}"


def build_code_chunk_candidates(*, content: str, content_bytes: bytes, tree: Tree, language: str,
                                  min_symbol_lines: int, max_symbol_lines: int, identifier_token_cap: int,
                                  call_token_cap: int, ast_node_sequence_cap: int) -> tuple:
    candidates = []
    filtered_count = 0
    root = tree.root_node
    if bool(getattr(root, "has_error", False)):
        return candidates, filtered_count
    spans = collect_symbol_spans(content_bytes, language, tree)
    if not spans:
        return candidates, filtered_count
    file_level_imports = _collect_file_level_import_snippets(content_bytes, root)
    spans_by_range = {(span.start_byte, span.end_byte): span for span in spans}
    stack = [root]
    while stack:
        node = stack.pop()
        stack.extend(reversed(list(node.children)))
        span = spans_by_range.get((int(node.start_byte), int(node.end_byte)))
        if span is None:
            continue
        raw_bytes = content_bytes[span.start_byte: span.end_byte]
        raw_code = raw_bytes.decode("utf-8", errors="ignore").strip()
        if not raw_code:
            filtered_count += 1
            continue
        line_count = span.line_end - span.line_start + 1
        if line_count < max(1, min_symbol_lines) or line_count > max(1, max_symbol_lines):
            filtered_count += 1
            continue
        if _contains_generated_marker(raw_code):
            filtered_count += 1
            continue
        normalized_code = _normalize_code(raw_code, raw_bytes, node)
        if not normalized_code.strip():
            filtered_count += 1
            continue
        identifier_tokens = _collect_identifier_tokens(content_bytes, node, cap=max(1, identifier_token_cap))
        if not identifier_tokens:
            regex_identifiers = IDENTIFIER_RE.findall(normalized_code)
            identifier_tokens = _ordered_unique(regex_identifiers, cap=max(1, identifier_token_cap))
        call_tokens = _collect_call_tokens(content_bytes, node, language=language, cap=max(1, call_token_cap))
        operator_tokens = _collect_operator_tokens(content_bytes, node)
        ast_node_sequence = _collect_ast_node_sequence(node, cap=max(1, ast_node_sequence_cap))
        structure_signature = _build_structure_signature(span.chunk_type, ast_node_sequence)
        anonymization_context = _build_anonymization_context(content_bytes, node, language)
        context_decorators = _extract_context_decorators(content_bytes, node, language)
        context_class_signature, context_parent_class = _extract_enclosing_class_context(content_bytes, node, language)
        context_exports = _extract_context_exports(raw_code, language, span.symbol_name)
        if language in {"javascript", "typescript"} and span.chunk_type == "function":
            header_parameter_symbols = _extract_js_ts_header_parameter_names(normalized_code)
            anonymization_context = AnonymizationContext(
                imported_symbols=anonymization_context.imported_symbols,
                parameter_symbols=anonymization_context.parameter_symbols | header_parameter_symbols,
                local_variable_symbols=anonymization_context.local_variable_symbols - header_parameter_symbols,
                local_function_symbols=anonymization_context.local_function_symbols,
                local_class_symbols=anonymization_context.local_class_symbols,
                decorator_symbols=anonymization_context.decorator_symbols,
            )
        control_flow_tags = _collect_control_flow_tags(ast_node_sequence=ast_node_sequence, symbol_name=span.symbol_name, call_tokens=call_tokens)
        if _is_trivial_candidate(span=span, node=node, language=language, normalized_code=normalized_code,
                                  identifier_tokens=identifier_tokens, call_tokens=call_tokens,
                                  ast_node_sequence=ast_node_sequence, structure_signature=structure_signature,
                                  nested_function_symbols=anonymization_context.local_function_symbols):
            filtered_count += 1
            continue
        anonymization_result = _anonymize_code(
            language=language, normalized_code=normalized_code, symbol_name=span.symbol_name,
            chunk_type=span.chunk_type, call_tokens=call_tokens,
            imported_symbols=anonymization_context.imported_symbols,
            parameter_symbols=anonymization_context.parameter_symbols,
            local_variable_symbols=anonymization_context.local_variable_symbols,
            local_function_symbols=anonymization_context.local_function_symbols,
            local_class_symbols=anonymization_context.local_class_symbols,
            decorator_symbols=anonymization_context.decorator_symbols,
        )
        anonymized_code = _canonicalize_named_arrow_function_code(anonymization_result.code, node_type=span.node_type, symbol_name=span.symbol_name)
        validation_status = "valid"
        if _has_unreplaced_local_occurrence(language=language, code=anonymized_code, replacements=anonymization_result.replacements):
            conservative_result = _anonymize_code(
                language=language, normalized_code=normalized_code, symbol_name=span.symbol_name,
                chunk_type=span.chunk_type, call_tokens=call_tokens,
                imported_symbols=anonymization_context.imported_symbols,
                parameter_symbols=anonymization_context.parameter_symbols,
                local_variable_symbols=set(), local_function_symbols=set(), local_class_symbols=set(),
                decorator_symbols=anonymization_context.decorator_symbols,
            )
            conservative_code = _canonicalize_named_arrow_function_code(conservative_result.code, node_type=span.node_type, symbol_name=span.symbol_name)
            if _has_unreplaced_local_occurrence(language=language, code=conservative_code, replacements=conservative_result.replacements):
                anonymized_code = normalized_code
                validation_status = "fallback_normalized"
            else:
                anonymized_code = conservative_code
                validation_status = "fallback_conservative"
        candidates.append(CodeChunkCandidate(
            chunk_type=span.chunk_type, symbol_type=span.symbol_type, symbol_name=span.symbol_name,
            param_count=span.param_count, line_start=span.line_start, line_end=span.line_end,
            node_type=span.node_type, raw_code=raw_code, normalized_code=normalized_code,
            anonymized_code=anonymized_code, identifier_tokens=identifier_tokens, call_tokens=call_tokens,
            operator_tokens=operator_tokens, control_flow_tags=control_flow_tags,
            structure_signature=structure_signature, ast_node_sequence=ast_node_sequence,
            raw_hash=hashlib.sha1(raw_code.encode("utf-8")).hexdigest(),
            normalized_hash=hashlib.sha1(normalized_code.encode("utf-8")).hexdigest(),
            anonymized_hash=hashlib.sha1(anonymized_code.encode("utf-8")).hexdigest(),
            validation_status=validation_status, context_imports=file_level_imports,
            context_decorators=context_decorators, context_class_signature=context_class_signature,
            context_parent_class=context_parent_class, context_exports=context_exports,
        ))
    return candidates, filtered_count


def anonymize_code(raw_code: str, language: str) -> str:
    """단일 코드 스니펫을 anonymize. 파싱 실패시 normalize된 코드 반환."""
    parser_key = LANGUAGE_TO_PARSER_KEY.get(language)
    if parser_key is None or get_parser is None:
        return raw_code
    try:
        parser = get_parser(parser_key)
        raw_bytes = raw_code.encode("utf-8")
        tree = parser.parse(raw_bytes)
    except Exception:
        return raw_code

    candidates, _ = build_code_chunk_candidates(
        content=raw_code,
        content_bytes=raw_bytes,
        tree=tree,
        language=language,
        min_symbol_lines=1,
        max_symbol_lines=10000,
        identifier_token_cap=200,
        call_token_cap=100,
        ast_node_sequence_cap=64,
    )
    if candidates:
        return max(candidates, key=lambda c: c.line_end - c.line_start).anonymized_code

    # fallback: normalize only
    root = tree.root_node
    return _normalize_code(raw_code, raw_bytes, root)
